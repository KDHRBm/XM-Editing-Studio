import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawn} from 'node:child_process';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const stage=path.join(root,'artifacts/XM剪辑台-csharp-win32-x64');
const exe=path.join(stage,'小马剪辑台.exe');
await fs.access(exe).catch(()=>{throw Error('Run npm run package to build the C# host first.');});
const child=spawn(exe,[],{cwd:stage,windowsHide:true,stdio:'inherit',env:{...process.env,XM_NATIVE_USER_DATA_DIR:path.join(root,'.local-profile-native')}});
child.on('error',error=>{console.error(error.message);process.exitCode=1;});
child.on('exit',code=>{process.exitCode=code??1;});
