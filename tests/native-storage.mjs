import fs from 'node:fs/promises';
import path from 'node:path';
import {spawn} from 'node:child_process';
import assert from 'node:assert/strict';
const root=process.cwd();
const folder=path.join(process.env.XM_TEST_ROOT || path.join(root,'.generated','native-storage'),`case-${Date.now()}`);
const legacy=path.join(folder,'旧版 profile'),native=path.join(folder,'新版 profile');
await fs.mkdir(native,{recursive:true});
const snapshot=path.join(native,'native-migration.json');
const run=(exe,args,env={})=>new Promise((resolve,reject)=>{
  const p=spawn(exe,args,{cwd:root,env:{...process.env,...env},windowsHide:true,stdio:['ignore','pipe','pipe']});
  let output='';p.stdout.on('data',b=>output+=b);p.stderr.on('data',b=>output+=b);
  const timer=setTimeout(()=>{p.kill();reject(Error('Migration process timed out'))},150000);
  p.on('error',reject);p.on('exit',code=>{clearTimeout(timer);resolve({code,output})});
});
const electron=path.join(root,'node_modules/electron/dist/electron.exe');
const exe=process.env.XM_TEST_HOST || path.join(root,'artifacts/XM剪辑台-csharp-win32-x64/小马剪辑台.exe');
assert.equal((await run(electron,['tests/native-storage-fixture.cjs'],{XM_MIGRATION_PROFILE:legacy})).code,0);
const exported=await run(electron,['scripts/export-legacy-state.cjs'],{XM_MIGRATION_PROFILE:legacy,XM_MIGRATION_OUTPUT:snapshot});
assert.equal(exported.code,0,exported.output);
const data=JSON.parse(await fs.readFile(snapshot,'utf8'));
assert.equal(data.localStorage['migration-fixture'],'第十三集 — Sr. López, espera...');
assert.equal(data.databases.reduce((n,db)=>n+db.stores.reduce((m,s)=>m+s.records.length,0),0),2);
const imported=await run(exe,['--verify-migration'],{XM_NATIVE_USER_DATA_DIR:native});
assert.equal(imported.code,0,imported.output);
const report=JSON.parse(await fs.readFile(path.join(native,'native-migration-report.json'),'utf8'));
assert.deepEqual(report,{localStorageKeys:2,databaseRecords:2});
await fs.access(path.join(native,'native-migrated.flag'));
const invalid=path.join(folder,'invalid');await fs.mkdir(invalid);await fs.writeFile(path.join(invalid,'native-migration.json'),'{}');
assert.equal((await run(exe,['--verify-migration'],{XM_NATIVE_USER_DATA_DIR:invalid})).code,1);
await assert.rejects(fs.access(path.join(invalid,'native-migrated.flag')));
console.log('PASS: legacy export → WebView2 verified import; Unicode, localStorage, tasks, indexed stores, empty DB; invalid snapshot rejected.');
